    /// <summary>
    /// Canvas锚定方式
    /// 定义Canvas在相机空间中的附着位置
    /// 用于控制UI画布在相机视野中的深度位置，决定UI渲染的远近层级
    /// 主要应用于世界空间Canvas的相机附着，影响UI元素与场景物体的遮挡关系和视觉深度
    /// </summary>
    public enum CanvasAnchor
    {
        /// <summary>
        /// 相机近平面附着
        /// 将Canvas附着在相机的近裁剪平面（Near Clip Plane）上
        /// 
        /// 技术原理：
        /// - Canvas位于相机最近渲染距离处
        /// - 距离相机的距离 = 相机的Near Clip Plane距离
        /// - UI元素始终显示在场景物体前方
        /// - 不会被任何场景物体遮挡
        /// 
        /// 视觉特性：
        /// - UI元素看起来最靠近相机
        /// - 显示尺寸相对较大（基于透视投影）
        /// - 不会与场景物体产生深度冲突
        /// - 始终保持在最上层渲染
        /// 
        /// 适用场景：
        /// - 主菜单界面（需要完全可见，不被遮挡）
        /// - 暂停菜单（覆盖游戏画面）
        /// - 提示框和通知（需要醒目显示）
        /// - 加载界面（始终可见）
        /// - HUD元素（血条、技能栏等主要UI）
        /// - 对话框和弹窗（需要优先显示）
        /// 
        /// 优势：
        /// - UI永远不会被场景物体遮挡
        /// - 渲染性能较好
        /// - 透视效果自然（近大远小）
        /// 
        /// 劣势：
        /// - 缺乏与场景的深度融合感
        /// - UI看起来始终"贴"在相机上
        /// - 不适合需要融入场景的UI元素
        /// 
        /// 示例：
        /// ```
        /// // 将Canvas附着在相机近平面
        /// canvas.renderMode = RenderMode.WorldSpace;
        /// canvas.worldCamera = mainCamera;
        /// canvas.planeDistance = mainCamera.nearClipPlane;
        /// ```
        /// </summary>
        CameraNear = 0,
        /// <summary>
        /// 相机远平面附着
        /// 将Canvas附着在相机的远裁剪平面（Far Clip Plane）上
        /// 
        /// 技术原理：
        /// - Canvas位于相机最远渲染距离处
        /// - 距离相机的距离 = 相机的Far Clip Plane距离
        /// - UI元素显示在场景物体后方
        /// - 可能被场景物体遮挡
        /// 
        /// 视觉特性：
        /// - UI元素看起来远离相机
        /// - 显示尺寸相对较小（基于透视投影）
        /// - 可被场景物体遮挡，产生景深感
        /// - 渲染顺序靠后
        /// 
        /// 适用场景：
        /// - 背景UI元素（如远景装饰）
        /// - 3D场景中的指示牌
        /// - 远处标记点
        /// - 需要融入场景的UI
        /// - 场景中的交互提示牌
        /// - 世界空间中的说明文字
        /// 
        /// 优势：
        /// - UI元素可融入3D场景
        /// - 产生真实的景深效果
        /// - 适合增强现实感的设计
        /// 
        /// 劣势：
        /// - UI可能被场景物体遮挡
        /// - 需要处理遮挡关系
        /// - 较小尺寸可能影响可读性
        /// 
        /// 示例：
        /// ```
        /// // 将Canvas附着在相机远平面
        /// canvas.renderMode = RenderMode.WorldSpace;
        /// canvas.worldCamera = mainCamera;
        /// canvas.planeDistance = mainCamera.farClipPlane;
        /// ```
        /// </summary>
        CameraFar = 1,
        /// <summary>
        /// 自定义距离
        /// 使用自定义的平面距离值，不限制在相机的近平面或远平面
        /// 
        /// 技术原理：
        /// - Canvas距离相机的位置由用户自定义
        /// - 距离值可以是近平面和远平面之间的任意值
        /// - 也可以超出近平面和远平面范围（可能导致不可见）
        /// - 提供最大的灵活性
        /// 
        /// 视觉特性：
        /// - UI位置可精确控制
        /// - 可实现UI与场景物体的精确遮挡关系
        /// - 支持动态调整距离实现动画效果
        /// - 可创造特殊的视觉深度效果
        /// 
        /// 适用场景：
        /// - 角色头顶的血条（跟随角色距离）
        /// - 3D空间中的交互按钮（固定世界位置）
        /// - 可拖拽的3D UI面板
        /// - 需要动态调整距离的特效UI
        /// - 浮空指示器（如NPC头顶的对话框）
        /// - 增强现实效果的UI元素
        /// - 需要精确深度控制的UI效果
        /// 
        /// 优势：
        /// - 完全可控，灵活性最高
