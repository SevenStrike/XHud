        /// - 按钮禁用：Recycler动效 = 无运动（直接隐藏）
        /// </summary>
        Recycler = 1
    }

    /// <summary>
    /// 元素的动画状态
    /// 定义UI元素当前的动画播放状态
    /// 用于状态机管理，控制UI元素在动画播放期间的行为表现
    /// 配合 HudElementMotionType 和 HudElementCreateState 使用，实现完整的UI元素生命周期管理
    /// </summary>
    public enum HudElementAnimateState
    {
        /// <summary>
        /// 静态状态
        /// 元素处于静止状态，无动画正在播放
        /// 
        /// 状态特征：
        /// - 动画已完成或尚未开始
        /// - 元素完全显示并可交互
        /// - 不占用动画系统资源
        /// - 可随时触发新的动画
        /// - 处于稳定的视觉呈现状态
        /// 
        /// 行为表现：
        /// - 可以响应用户输入（点击、悬停等）
        /// - 位置、大小、颜色等属性保持恒定
        /// - 无任何变换或透明度变化
        /// - 处于可交互的最终状态
        /// 
        /// 触发时机：
        /// - 元素创建动画（Creator）完成后
        /// - 元素回收动画（Recycler）开始前
        /// - 动画被取消或中断后
        /// - 元素从对象池取出并完成初始化后
        /// - 手动停止动画时
        /// 
        /// 适用场景：
        /// - UI面板完全展开后
        /// - 按钮等待用户点击时
        /// - 列表项正常显示时
        /// - 提示框完全显示后
        /// - 元素处于待命状态时
        /// 
        /// 状态转换：
        /// - Static → Animating：当触发新的动画时
        /// - Static → Recycled：当元素被直接回收（无动画）时
        /// 
        /// 示例：
        /// ```
        /// // 元素完成创建动效后进入静态状态
        /// void OnCreatorMotionComplete()
        /// {
        ///     elementState = HudElementAnimateState.Static;
        ///     EnableInteraction(true);  // 启用交互
        /// }
        /// ```
        /// </summary>
        Static,

        /// <summary>
        /// 动画播放中状态
        /// 元素正在播放动画，处于过渡变化中
        /// 
        /// 状态特征：
        /// - 动画正在执行中
        /// - 元素属性正在变化（位置、旋转、缩放、颜色、透明度等）
        /// - 可能处于半可见或中间状态
        /// - 通常禁止或限制用户交互
        /// - 占用动画系统资源
        /// 
        /// 行为表现：
        /// - 通常禁止用户输入（防止动画期间误操作）
        /// - 位置、大小、颜色等属性持续变化
        /// - 可能处于不可见、半透明或变形状态
        /// - 动画播放完成后自动切换到 Static 状态
        /// - 可设置是否允许中断或取消
        /// 
        /// 触发时机：
        /// - Creator 动效开始播放时
        /// - Recycler 动效开始播放时
        /// - 任何过渡动画（Tween）开始时
        /// - 手动调用动画播放方法时
        /// 
        /// 适用场景：
        /// - 面板弹出/收起动画期间
        /// - 元素飞入/飞出过程中
        /// - 淡入/淡出过渡期间
        /// - 缩放动画播放时
        /// - 旋转动画播放时
        /// - 颜色渐变过程中
        /// 
        /// 状态转换：
        /// - Animating → Static：动画播放完成时
        /// - Animating → Recycled：动画完成后回收时
        /// - Animating → Animating：连续播放多个动画时（链式动画）
        /// 
        /// 注意事项：
        /// - 动画播放期间应禁用 RaycastTarget，避免误触
        /// - 可设置动画优先级，高优先级动画可中断低优先级动画
        /// - 需要处理动画被强制中断的情况
        /// - 动画期间应避免状态查询导致的逻辑错误
        /// 
        /// 示例：
        /// ```
        /// // 播放回收动效时进入动画状态
        /// void PlayRecyclerMotion()
        /// {
        ///     elementState = HudElementAnimateState.Animating;
        ///     EnableInteraction(false);  // 禁用交互
        ///     
        ///     // 播放动画...
        ///     
        ///     void OnAnimationComplete()
        ///     {
        ///         // 动画完成后回收元素，不再切换到Static
        ///         RecycleElement();
        ///     }
        /// }
        /// 
        /// // 播放创建动效
        /// void PlayCreatorMotion()
        /// {
        ///     elementState = HudElementAnimateState.Animating;
        ///     EnableInteraction(false);  // 动画期间禁用交互
        ///     
        ///     // 播放动画...
        ///     
        ///     void OnAnimationComplete()
        ///     {
        ///         elementState = HudElementAnimateState.Static;
        ///         EnableInteraction(true);  // 动画完成后启用交互
        ///     }
        /// }
        /// ```
        /// </summary>
        Animating
    }

